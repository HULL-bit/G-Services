INSERT INTO favori (id_personne, id_service, date_ajout, etat)
SELECT p.id_personne, s.id_service, now() - (random() * interval '20 days'), TRUE
FROM personne p
JOIN LATERAL (
    SELECT id_service FROM service
    WHERE etat AND valide
    ORDER BY random() LIMIT 3
) s ON TRUE
WHERE p.login IN ('awa.diop', 'karim.ba', 'marie.ndiaye', 'cl.sarr', 'cl.toure', 'cl.wade', 'cl.gomis')
ON CONFLICT (id_personne, id_service) DO NOTHING;
