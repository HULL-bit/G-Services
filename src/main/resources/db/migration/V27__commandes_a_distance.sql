-- ============================================================================
--  G-SERVICES — V27 : commandes à distance (hors UML)
--
--  Certains services acceptent la vente en ligne (service.commande_a_distance).
--  Un client connecté passe une Commande (n LigneCommande) sur un tel service ;
--  l'administrateur ou le fournisseur propriétaire la traite (branche 7000).
-- ============================================================================

-- ---------------------------------------------------- drapeau service -------
ALTER TABLE service ADD COLUMN IF NOT EXISTS commande_a_distance BOOLEAN NOT NULL DEFAULT FALSE;

-- ---------------------------------------------------- tables ----------------
CREATE TABLE commande (
    id_commande        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference          VARCHAR(30)   NOT NULL UNIQUE,
    date_commande      TIMESTAMP     NOT NULL DEFAULT now(),
    statut             VARCHAR(20)   NOT NULL DEFAULT 'NOUVELLE',
    montant_total      NUMERIC(12,2) NOT NULL DEFAULT 0,
    commentaire        VARCHAR(1000),
    adresse_livraison  VARCHAR(255),
    telephone_contact  VARCHAR(30),
    etat               BOOLEAN       NOT NULL DEFAULT TRUE,
    id_client          BIGINT        NOT NULL,
    id_service         BIGINT        NOT NULL,
    CONSTRAINT fk_commande_client  FOREIGN KEY (id_client)  REFERENCES personne (id_personne),
    CONSTRAINT fk_commande_service FOREIGN KEY (id_service) REFERENCES service (id_service)
);
CREATE INDEX idx_commande_client  ON commande (id_client);
CREATE INDEX idx_commande_service ON commande (id_service);
CREATE INDEX idx_commande_statut  ON commande (statut);

CREATE TABLE ligne_commande (
    id_ligne_commande  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantite           INTEGER       NOT NULL CHECK (quantite > 0),
    prix_unitaire      NUMERIC(12,2) NOT NULL,
    etat               BOOLEAN       NOT NULL DEFAULT TRUE,
    id_commande        BIGINT        NOT NULL,
    id_article         BIGINT        NOT NULL,
    CONSTRAINT fk_ligne_commande_commande FOREIGN KEY (id_commande) REFERENCES commande (id_commande) ON DELETE CASCADE,
    CONSTRAINT fk_ligne_commande_article  FOREIGN KEY (id_article)  REFERENCES article (id_article)
);
CREATE INDEX idx_ligne_commande_commande ON ligne_commande (id_commande);

-- ---------------------------------------------------- branche 7000 ----------
INSERT INTO branche_permission (code, libelle, icone, niveau, etat)
VALUES ('7000', 'Commandes', 'pi pi-shopping-cart', 7, TRUE)
ON CONFLICT (code) DO NOTHING;

INSERT INTO permission (code, libelle, action_autorisee, reference, niveau, id_branche_permission)
SELECT v.code, v.libelle, v.action, '/admin/commandes/commandes.xhtml', v.niveau, b.id_branche_permission
FROM (VALUES
    ('7001', 'Consulter les commandes', 'LIRE',       0),
    ('7002', 'Traiter les commandes',   'MODIFIER',   1),
    ('7003', 'Annuler une commande',    'SUPPRIMER',  2),
    ('7004', 'Exporter les commandes',  'EXPORTER',   3)
) AS v(code, libelle, action, niveau)
JOIN branche_permission b ON b.code = '7000'
ON CONFLICT (code) DO NOTHING;

-- SUPER_ADMIN : tout
INSERT INTO role_profil (id_profil, id_permission)
SELECT p.id_profil, pe.id_permission
FROM profil p CROSS JOIN permission pe
WHERE p.libelle = 'SUPER_ADMIN' AND pe.code IN ('7001','7002','7003','7004')
ON CONFLICT (id_profil, id_permission) DO NOTHING;

-- ADMIN / GESTIONNAIRE : consulter, traiter, exporter
INSERT INTO role_profil (id_profil, id_permission)
SELECT p.id_profil, pe.id_permission
FROM profil p CROSS JOIN permission pe
WHERE p.libelle IN ('ADMIN','GESTIONNAIRE') AND pe.code IN ('7001','7002','7004')
ON CONFLICT (id_profil, id_permission) DO NOTHING;

