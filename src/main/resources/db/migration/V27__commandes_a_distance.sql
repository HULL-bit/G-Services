INSERT INTO role_profil (id_profil, id_permission)
SELECT p.id_profil, pe.id_permission
FROM profil p CROSS JOIN permission pe
WHERE p.libelle = 'PRESTATAIRE' AND pe.code IN ('7001','7002')
ON CONFLICT (id_profil, id_permission) DO NOTHING;

INSERT INTO profil_branche_permission (id_profil, id_branche_permission)
SELECT p.id_profil, b.id_branche_permission
FROM profil p JOIN branche_permission b ON b.code = '7000'
WHERE p.libelle IN ('SUPER_ADMIN','ADMIN','GESTIONNAIRE','PRESTATAIRE')
ON CONFLICT DO NOTHING;

-- ---------------------------------------------------- démo ------------------
--  Services « vendables en ligne » : restauration, mode & textile, hôtellerie,
--  artisanat, événementiel (produits livrables / réservables à distance).
UPDATE service SET commande_a_distance = TRUE
WHERE id_categorie_service IN (
    SELECT id_categorie_service FROM categorie_service
    WHERE libelle IN ('Restauration', 'Mode & textile', 'Hôtellerie', 'Artisanat', 'Événementiel')
);

--  Quelques commandes de démonstration (clients cl.* / awa.diop … sur des
--  services commandables), 2 articles chacune, statuts variés.
INSERT INTO commande (reference, statut, montant_total, adresse_livraison, telephone_contact, id_client, id_service)
SELECT 'CMD-TMP' || d.rn,
       (ARRAY['NOUVELLE','CONFIRMEE','EN_PREPARATION','LIVREE','NOUVELLE'])[1 + (d.rn % 5)],
       0,
       d.quartier || ', Dakar',
       '+221 77 ' || lpad((100 + d.rn)::text, 3, '0') || ' 00 00',
       d.id_client, d.id_service
FROM (
    SELECT row_number() OVER () AS rn, cl.id_personne AS id_client, s.id_service,
           (ARRAY['Médina','Plateau','Sacré-Cœur','Almadies','Yoff','Ouakam','Point E','Mermoz'])[1 + (row_number() OVER () % 8)] AS quartier
    FROM (SELECT id_personne FROM personne WHERE login LIKE 'cl.%' OR login IN ('awa.diop','karim.ba','marie.ndiaye')) cl
    CROSS JOIN LATERAL (
        SELECT s2.id_service FROM service s2
        WHERE s2.commande_a_distance AND s2.etat AND s2.id_service_parent IS NULL
          AND EXISTS (
              SELECT 1 FROM article ar
              JOIN produit pr ON pr.id_produit = ar.id_produit
              JOIN catalogue ca ON ca.id_catalogue = pr.id_catalogue
              WHERE ca.id_service = s2.id_service AND ar.etat AND ar.disponibilite)
        ORDER BY (cl.id_personne * 7 + s2.id_service) % 97
        LIMIT 1
    ) s
    LIMIT 12
) d;

INSERT INTO ligne_commande (quantite, prix_unitaire, id_commande, id_article)
SELECT 1 + (c.id_commande % 3),
       a.prix,
       c.id_commande,
       a.id_article
FROM commande c
CROSS JOIN LATERAL (
    SELECT ar.id_article, ar.prix
    FROM article ar
    JOIN produit pr ON pr.id_produit = ar.id_produit
    JOIN catalogue ca ON ca.id_catalogue = pr.id_catalogue
    WHERE ca.id_service = c.id_service AND ar.etat AND ar.disponibilite
    ORDER BY ar.id_article
    LIMIT 2
) a
WHERE c.reference LIKE 'CMD-TMP%';

UPDATE commande c
SET montant_total = COALESCE((
    SELECT sum(l.quantite * l.prix_unitaire) FROM ligne_commande l WHERE l.id_commande = c.id_commande
), 0)
WHERE c.reference LIKE 'CMD-TMP%';

UPDATE commande SET reference = 'CMD-' || lpad(id_commande::text, 6, '0')
WHERE reference LIKE 'CMD-TMP%';
